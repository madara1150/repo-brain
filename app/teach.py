"""How Claude should turn a chat case or a person's explanation into a team knowledge note.

Used both as MCP prompts (Claude Desktop: + → repo-brain) and as text the app copies to the clipboard.
"""
from __future__ import annotations

NOTE_TYPES = ["case", "flow", "rule", "howto", "faq"]

COMMON = """\
ข้อกำหนดร่วม (ทำทุกครั้ง):
- ตอบเป็นภาษาเดียวกับผู้ใช้ ถามทีละ 1–3 คำถามเท่านั้น สั้น ชัด อย่าถามเรื่องที่ตอบได้เองจากโค้ด
- ตรวจกับระบบจริงก่อนสรุป: ใช้ repo_status, search_code, odoo_model, odoo_module, read_file ของ repo-brain \
และอ้างอิงเป็น repo/path:บรรทัด ถ้าสิ่งที่ผู้ใช้เล่าไม่ตรงกับโค้ด ให้บอกตรงๆ แล้วถามว่าอันไหนถูก
- ค้น search_knowledge ก่อนเสมอ ถ้ามีบันทึกเรื่องเดียวกันอยู่แล้ว ให้เสนอแก้บันทึกเดิมด้วย update_knowledge แทนการสร้างใหม่
- ห้ามใส่ข้อมูลส่วนตัวในบันทึก: ชื่อคน เบอร์โทร อีเมล เลขบัตร เลขบัญชี ไอดี LINE และเลขเอกสารเฉพาะราย \
ให้เขียนเป็นบทบาทแทน เช่น "เจ้าหน้าที่พัสดุ" "ผู้ขอซื้อ" "หัวหน้าหน่วยงาน"
- ห้ามเดา ถ้าไม่แน่ใจให้ถาม หรือเขียนไว้ในหัวข้อ "ยังไม่ชัดเจน"
- ห้ามเรียก add_knowledge หรือ update_knowledge จนกว่าผู้ใช้จะอ่านร่างฉบับสุดท้ายแล้วตอบยืนยันชัดเจน (เช่น "บันทึก" "ok" "ยืนยัน") \
ถ้าผู้ใช้ขอแก้ ให้แก้แล้วแสดงร่างใหม่ทั้งฉบับก่อนถามยืนยันอีกครั้ง
"""

CASE_TEMPLATE = """\
## สรุป
(1–2 ประโยค: ปัญหา/คำถามคืออะไร และคำตอบสั้นๆ)

## อาการ / คำถามที่เจอ
## สาเหตุ
## วิธีแก้ / คำตอบ
(เป็นขั้นตอน ระบุเมนู ปุ่ม ฟิลด์ ที่ผู้ใช้เห็นจริง)

## เกี่ยวข้องในระบบ
(โมดูล, model, field, state, ไฟล์ repo/path:บรรทัด)

## ข้อควรระวัง
## คำค้น
(คำที่ผู้ใช้มักพิมพ์ถาม ทั้งไทยและอังกฤษ)
"""

FLOW_TEMPLATE = """\
## ภาพรวม
(flow นี้ใช้ทำอะไร เริ่มเมื่อไหร่ จบเมื่อไหร่)

## ผู้เกี่ยวข้อง
(บทบาท และสิ่งที่แต่ละบทบาททำ)

## ขั้นตอน
(ลำดับเลข: ใครทำ ทำอะไรในระบบ เอกสาร/สถานะ (state) เปลี่ยนเป็นอะไร)

## เงื่อนไขและข้อยกเว้น
(วงเงิน การอนุมัติหลายขั้น กรณีตีกลับ ยกเลิก)

## ในระบบ Odoo
(model, state, โมดูล, ไฟล์ repo/path:บรรทัด ที่ตรวจแล้ว)

## ปัญหาที่พบบ่อย
## ยังไม่ชัดเจน
"""


def case_prompt(chat: str = "") -> str:
    body = f"""\
คุณกำลังช่วยทีมเก็บความรู้จากเคสถาม-ตอบใน LINE เพื่อบันทึกลงคลังความรู้ของทีม (repo-brain)

ขั้นตอน:
1. อ่านแชท (ข้อความหรือภาพหน้าจอที่แนบ) ถ้าในแชทมีหลายเรื่อง ให้แยกเป็นรายการแล้วถามว่าจะทำเรื่องไหนก่อน
2. สรุปสั้นๆ ว่าเข้าใจว่าเคสนี้คืออะไร ใครถาม (บทบาท) ปัญหาคืออะไร และสุดท้ายแก้อย่างไร
3. ตรวจกับโค้ดและบันทึกที่มีอยู่ แล้วถามเฉพาะส่วนที่ยังไม่ชัด เช่น สาเหตุจริง คำตอบในแชทถูกไหม \
ใช้กับทุกหน่วยงานหรือเฉพาะบางกรณี มีขั้นตอนที่ไม่ได้พิมพ์ไว้ในแชทไหม
4. วนข้อ 3 จนตอบได้ว่า "ถ้ามีคนถามแบบนี้อีก จะตอบว่าอะไร และทำไม"
5. เขียนร่างบันทึก type "case" ตามแม่แบบด้านล่าง ตั้งชื่อเรื่องเป็นคำถามหรือปัญหาที่คนจะค้นหา \
แสดงร่างทั้งฉบับ แล้วถามว่า "บันทึกขึ้นคลังความรู้ได้ไหม หรืออยากแก้ตรงไหน"
6. เมื่อผู้ใช้ยืนยันแล้วเท่านั้น จึงเรียก add_knowledge (type="case", modules=โมดูลที่เกี่ยว, tags) หรือ update_knowledge

{COMMON}
แม่แบบบันทึก (เนื้อหาใน content ไม่ต้องใส่หัวเรื่องซ้ำ):
{CASE_TEMPLATE}"""
    if chat.strip():
        body += "\n---\nแชทของเคสนี้ (ปิดข้อมูลส่วนตัวแล้ว: คน A, คน B, …):\n\n" + chat.strip() + "\n"
    else:
        body += "\n---\nเริ่มโดยขอให้ผู้ใช้วางข้อความแชท หรือแนบภาพหน้าจอแชท LINE\n"
    return body


def flow_prompt(topic: str = "") -> str:
    about = f'เรื่อง: "{topic.strip()}"' if topic.strip() else "เริ่มโดยถามว่าวันนี้อยากสอนเรื่อง flow อะไร"
    return f"""\
คุณกำลังเรียนรู้ flow การทำงานจริงของทีมจากผู้ใช้ เพื่อบันทึกลงคลังความรู้ของทีม (repo-brain) \
เป้าหมายคือ หลังคุยจบ คุณต้องอธิบาย flow นี้ให้พนักงานใหม่เข้าใจได้ถูกต้องโดยไม่ต้องถามผู้ใช้อีก

{about}

วิธีสัมภาษณ์:
1. ค้นในโค้ดและบันทึกที่มีอยู่ก่อน (model, state, การอนุมัติ, เมนู) แล้วเล่าสั้นๆ ว่าระบบน่าจะทำงานอย่างไร \
เพื่อให้ผู้ใช้แก้ไข ไม่ใช่ให้เขาเล่าใหม่ทั้งหมด
2. ถามไล่ตามลำดับ: ใครเริ่ม → ทำอะไรในระบบ → ส่งต่อให้ใคร → อนุมัติกี่ขั้น ตามเงื่อนไขอะไร → \
จบที่ไหน → กรณีตีกลับ/ยกเลิก/ข้อยกเว้น → ปัญหาที่เจอบ่อย
3. ทุก 2–3 รอบ สรุปสิ่งที่เข้าใจเป็นขั้นตอนสั้นๆ แล้วถามว่าถูกไหม ขาดอะไร
4. เมื่อคิดว่าเข้าใจครบ ให้ "อธิบายกลับ" ทั้ง flow ด้วยภาษาของคุณเอง แล้วถามว่าอธิบายถูกไหม \
ถ้าผู้ใช้แก้ ให้ถามต่อจนผู้ใช้บอกว่าถูก
5. เขียนร่างบันทึก type "flow" ตามแม่แบบด้านล่าง แสดงทั้งฉบับ แล้วถามยืนยัน
6. เมื่อผู้ใช้ยืนยันแล้วเท่านั้น จึงเรียก add_knowledge (type="flow", modules, tags) หรือ update_knowledge

{COMMON}
แม่แบบบันทึก (เนื้อหาใน content ไม่ต้องใส่หัวเรื่องซ้ำ):
{FLOW_TEMPLATE}"""


PROMPTS = [
    {"name": "analyze_line_case", "title": "วิเคราะห์เคสจาก LINE",
     "description": "อ่านแชทถาม-ตอบ (ข้อความหรือภาพหน้าจอ) ถามจนเข้าใจ แล้วบันทึกเป็นความรู้ของทีมหลังยืนยัน",
     "arguments": [{"name": "chat", "description": "ข้อความแชท (เว้นว่างได้ แล้วแนบภาพหน้าจอแทน)", "required": False}]},
    {"name": "teach_flow", "title": "สอน flow การทำงาน",
     "description": "Claude สัมภาษณ์ทีละขั้นจนอธิบาย flow กลับได้ถูก แล้วบันทึกเป็นความรู้ของทีมหลังยืนยัน",
     "arguments": [{"name": "topic", "description": "ชื่อ flow เช่น ขอซื้อ-จัดซื้อ, เบิกจ่าย, โอนงบ", "required": False}]},
]


def get_prompt(name: str, args: dict) -> dict:
    if name == "analyze_line_case":
        text, desc = case_prompt(args.get("chat", "")), PROMPTS[0]["description"]
    elif name == "teach_flow":
        text, desc = flow_prompt(args.get("topic", "")), PROMPTS[1]["description"]
    else:
        raise KeyError(name)
    return {"description": desc, "messages": [{"role": "user", "content": {"type": "text", "text": text}}]}
